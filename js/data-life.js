/* =========================================================
   종합 해설 — rec: { level, budget, spent, earned, picks:[{id,status}] }
   반환: [돈의 흐름, 아이의 마음, 사회 속 자리, 생각할 질문]
   ========================================================= */
GL.LIFE_SUMMARY = function (rec) {
  var money = GL.util.money;
  var picks = rec.picks || [];
  var s = GL.sim.summarize(picks);
  var earned = Number(rec.earned) || 0;
  var base = GL.LEVELS[rec.level] ? GL.LEVELS[rec.level].budget : 0;

  // 결과별로 쓴 돈 계산 (L1 국가 지원 무료 1개는 가격 0으로)
  var okM = 0, noneM = 0, sideM = 0, treatOkM = 0, enhM = 0, freeUsed = false;
  picks.forEach(function (p) {
    var o = GL.optById[p.id];
    if (!o) return;
    var price = o.price;
    if (rec.level === 1 && o.tag === 'treat' && !freeUsed) { price = 0; freeUsed = true; }
    if (p.status === 'ok') okM += price;
    if (p.status === 'none') noneM += price;
    if (p.status === 'side') sideM += price;
    if (p.status === 'ok' && o.tag === 'treat') treatOkM += price;
    if (o.tag === 'enhance') enhM += price;
  });
  var noneN = picks.filter(function (p) { return p.status === 'none'; }).length;
  var hasPersonality = GL.PERSONALITY_IDS.some(function (id) { return s.ids[id]; });
  var have = base + earned;
  var minPrice = Math.min.apply(null, GL.OPTIONS.map(function (o) { return o.price; }));
  var haveLine = earned > 0
    ? '원래 예산 ' + money(base) + '에 부모가 아르바이트로 번 ' + money(earned) + '을 더해 ' + money(have) + '이 있었어요.'
    : '부모에게 주어진 돈은 ' + money(base) + '이었어요.';

  /* ---- 1. 돈의 흐름 ---- */
  var p1;
  if (s.total === 0 && have < minPrice) {
    p1 = haveLine + ' 가장 싼 치료도 ' + money(minPrice) + '이었어요. 이 집은 유전자를 "고르지 않은" 게 아니라 "고를 수 없었어요".' +
      (rec.level === 2 ? ' 국가 지원의 기준선보다 조금 위에 있었다는 이유로요.' : '');
  } else if (s.total === 0) {
    p1 = haveLine + ' 고를 수 있는 돈이 있었지만, 부모는 아무것도 고르지 않았어요. 이 아이는 부모에게서 받은 그대로의 유전자로 태어났어요.';
  } else if (rec.level === 1 && s.total === 1 && freeUsed) {
    p1 = '이 집에 허락된 선택은 국가가 지원한 치료 하나뿐이었어요.' +
      (earned > 0 ? ' 부모가 아르바이트로 ' + money(earned) + '을 벌었지만 더 고를 수 있는 건 없었어요.' : '') +
      ' 고를 수 있는 것이 하나뿐일 때, 부모는 가장 꼭 필요한 것을 골랐어요.';
  } else {
    p1 = haveLine + (rec.spent >= have ? ' 부모는 그 돈을 모두 썼어요.' : ' 그중 ' + money(rec.spent) + '을 썼어요.');
    if (earned > 0 && base < minPrice) p1 += ' 원래 예산으로는 아무것도 살 수 없었으니, 이 아이가 받은 편집은 모두 부모가 일해서 번 돈으로 산 것이에요.';
    if (noneM > 0) p1 += ' ' + money(noneM) + '은 아무 효과가 없었어요.';
    if (sideM > 0) p1 += ' ' + money(sideM) + '은 예상하지 못한 변화를 남겼어요.';
    if ((noneM > 0 || sideM > 0) && treatOkM > 0) {
      p1 += ' 이 아이의 삶을 실제로 지켜 준 건 ' + money(treatOkM) + '짜리 치료였어요.';
    } else if (enhM > rec.spent / 2) {
      p1 += ' 쓴 돈의 대부분은 병을 막는 데가 아니라 아이를 "더 낫게" 만드는 데 들어갔어요.';
    }
  }

  /* ---- 2. 아이의 마음 ---- */
  var p2;
  if (s.side > 0) {
    p2 = '아이의 몸에는 누구도 바라지 않았던 변화가 남았어요. 아이는 부모를 원망하지 않으려 애쓰지만, 그 결정에 자신의 목소리가 없었다는 사실은 지워지지 않아요.';
  } else if (hasPersonality) {
    p2 = '아이는 자신의 성격 중 어디까지가 "나"이고 어디부터가 "부모가 고른 것"인지 자주 헷갈려요. 좋은 성격을 가졌는데도, 그게 온전히 자기 것이라고 느끼기 어려워요.';
  } else if (noneN > 0 && noneN >= s.total / 2) {
    p2 = '건강하게 자랐지만, 아이가 기억하는 건 "실패한 편집"에 대한 부모의 아쉬움이에요. 효과가 없었다는 사실보다, 기대받았다는 사실이 더 오래 남았어요.';
  } else if (s.enhance >= 3) {
    p2 = '아이는 무엇을 잘해도 칭찬보다 "원래 그렇게 태어났잖아"라는 말을 더 많이 들었어요. 노력한 날들이 유전자 뒤에 가려지는 게 아이에게는 가장 큰 상처예요.';
  } else if (s.enhance >= 1) {
    p2 = '아이는 남들보다 조금 앞서 출발했다는 걸 알아요. 그래서 이긴 날에도 마음 한쪽이 불편하고, 진 친구에게 미안할 때가 있어요.';
  } else if (s.total > 0) {
    p2 = '큰 병 없이 자란 아이는 부모에게 고마워해요. 하지만 같은 병을 가진 친구가 여전히 병원에 다니는 걸 보며, "왜 나만"이라는 미안함도 함께 품고 있어요.';
  } else {
    p2 = '아이는 자신이 모자라다고 생각하지 않아요. 그런데 사회는 자꾸 "편집 안 한 사람"이라는 이름표를 붙이고, 아이는 그 이름표와 싸우며 자랐어요.';
  }

  /* ---- 3. 2065년 사회 속 자리 ---- */
  var p3;
  if (s.total === 0) {
    p3 = '2065년, 신입사원의 87%가 편집 출신인 사회에서 이 아이는 소수가 되었어요. 능력이 아니라 "출발선"으로 먼저 평가받는 자리예요.';
  } else if (rec.level >= 4 && s.enhance >= 3) {
    p3 = '이 아이는 출발선부터 앞에 서 있어요. 하지만 사람들은 이 아이의 성취를 노력보다 부모의 지갑 덕분으로 여겨요. 앞선 자리가 늘 편한 자리는 아니에요.';
  } else if (s.enhance === 0) {
    p3 = '건강하게 자랐지만, 능력을 편집한 친구들과의 경쟁에서는 평범한 자리에 서 있어요. 이 사회에서 "건강하다"는 건 이제 시작선일 뿐이에요.';
  } else if (noneN > 0 && noneN >= s.total / 2) {
    p3 = '2065년, 신입사원의 87%가 편집 출신인 사회에서 이 아이는 "편집했지만 티가 안 나는" 애매한 자리에 서 있어요.';
  } else {
    p3 = '이 아이는 남들보다 한 발 앞선 자리에 서 있어요. 이 사회에서 그 한 발은 입시와 취업에서 점점 큰 차이가 돼요. 그리고 그 한 발을 살 수 없었던 친구들은 같은 출발선에 서 보지도 못했어요.';
  }

  /* ---- 4. 생각할 질문 ---- */
  var p4;
  if (s.total === 0 && rec.level <= 2) p4 = '이 아이가 가진 것 중, 돈으로 살 수 없었던 것은 무엇일까요?';
  else if (s.side > 0) p4 = '아이에게 묻지 않고 내린 결정의 결과는 누가 책임져야 할까요?';
  else if (hasPersonality) p4 = '부모가 고른 성격도 "나"라고 할 수 있을까요?';
  else if (noneN > 0 && noneN >= s.total / 2) p4 = '부모가 정말로 사고 싶었던 것은 무엇이었을까요?';
  else if (s.enhance >= 3) p4 = '이 아이의 성공은 누구의 것일까요?';
  else if (s.enhance === 0) p4 = '이 치료를 모든 아이가 받을 수 있으려면 무엇이 필요할까요?';
  else p4 = '"조금 앞선 출발"은 공정한 경쟁일까요?';

  return [p1, p2, p3, p4];
};
